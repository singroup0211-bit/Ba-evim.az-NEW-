export type VillaCategory = 'bag_evi' | 'dag_kotteci' | 'denizkenari' | 'seher_menzil';

export type VerificationBadgeType = 'in_person_verified' | 'document_verified' | 'pending';

export interface Villa {
  id: string;
  title: string;
  location: string;
  region: 'Bakı' | 'Quba' | 'Qəbələ' | 'Naxçıvan' | 'Gəncə' | 'İsmayıllı' | 'Şəki';
  zone: string;
  category: VillaCategory;
  type: 'Günlük' | 'Aylıq' | 'Satış';
  
  // Dinamik qiymətləndirmə (Həftəiçi, Həftəsonu, Bayram)
  price: number; // Cari baza qiymət
  weekdayPrice: number; // Bazar ertəsi - Cümə axşamı
  weekendPrice: number; // Cümə - Bazar
  holidayPrice: number; // Novruz, Yeni il, Qurban, Zəfər günü və s.
  period: 'gün' | 'ay' | 'satış';
  
  // Təqvim və dolu günlər
  bookedDates: string[]; // YYYY-MM-DD formatında dolu günlər
  customDatePricing?: Record<string, number>; // Xüsusi günlər üçün fərdi qiymət
  
  bedrooms: number;
  bathrooms: number;
  landArea: number; // sot
  houseArea: number; // kv.m
  capacity: number; // nəfər
  rating: number;
  reviewsCount: number;
  featured: boolean;
  hasPool: boolean;
  poolType: 'İsidilən filtirlənmiş' | 'Açıq dağ mənzərəli' | 'Qapalı spa' | 'Təbii bulaq suyu';
  hasSauna: boolean;
  hasBilliards: boolean;
  viewType: 'Dağ & Meşə' | 'Dəniz Sahili' | 'Göl Mənzərəsi' | 'Bağ & Çay';
  badge?: string;
  imageUrl: string;
  tags: string[];
  description: string;
  
  // Yerli bazar üçün xüsusi meyarlar
  features: VillaFeatures;
  
  // "Yoxlanılmış Ev" (Verified) və sənəd doğrulaması
  verificationStatus: VerificationBadgeType;
  verificationDetails: {
    kupchaNumber?: string;
    inspectorName?: string;
    verifiedAt?: string;
    videoTourUrl?: string;
    notes?: string;
  };
  
  // Qapalı əlaqə (Yalnız 10% behdən sonra açılır)
  hostContact: {
    name: string;
    phone: string;
    maskedPhone: string;
    whatsapp: string;
    fullAddress: string;
  };
}

